//! MySQL / MariaDB adapter backed by `sqlx::MySqlPool`.
//!
//! The store logic lives once in the `stores::sqlx_stores` macro; this module
//! supplies only the MySQL specifics — connection setup, the pool/row types,
//! the migration path, the no-op `?` placeholder rewriter (`common::ph_mysql`),
//! and the `txn` take strategy. The single sqlx `MySql` driver serves both
//! MySQL and MariaDB, so this one adapter covers both servers.
//!
//! Unlike Postgres and SQLite, MySQL has no `DELETE … RETURNING`, so the atomic
//! delete-and-return on the ephemeral stores runs as `SELECT … FOR UPDATE`
//! followed by `DELETE` inside a transaction (`take: txn`); see the
//! `sqlx_take` macro in `stores`. Timestamps are stored as `DATETIME(6)` rather
//! than `TIMESTAMP` so sub-second TTLs survive and the column spans years
//! outside `TIMESTAMP`'s 1970–2038 epoch range. sqlx pins the session
//! `time_zone` to `+00:00` by default, so `DateTime<Utc>` round-trips as UTC.
//! The shared storage-conformance suite (`tests/mysql`) runs the same
//! assertions against this expansion as against the Postgres and SQLite ones.

use sqlx::MySqlPool;
use sqlx::mysql::MySqlPoolOptions;

/// MySQL / MariaDB storage adapter. Construct once at startup and hand
/// `all_stores()` to `AuthService::builder`, or pull individual stores via the
/// helpers generated by the `stores::sqlx_stores` macro when wiring managers
/// by hand.
#[derive(Clone)]
pub struct MySqlStorage {
    pool: MySqlPool,
}

impl MySqlStorage {
    /// Pool size [`connect`](Self::connect) opens. A conservative default;
    /// hosts that need different tuning build their own pool and use
    /// [`from_pool`](Self::from_pool).
    pub const DEFAULT_MAX_CONNECTIONS: u32 = 8;

    /// Open a pool against `url`, e.g.
    /// `"mysql://user:pass@host:3306/db"`. Opens
    /// [`DEFAULT_MAX_CONNECTIONS`](Self::DEFAULT_MAX_CONNECTIONS) connections;
    /// use [`from_pool`](Self::from_pool) for custom tuning.
    pub async fn connect(url: &str) -> Result<Self, sqlx::Error> {
        let pool = MySqlPoolOptions::new()
            .max_connections(Self::DEFAULT_MAX_CONNECTIONS)
            .connect(url)
            .await?;
        Ok(Self { pool })
    }

    /// Construct directly from an already-built pool. Useful when the
    /// host wants custom pool tuning.
    pub fn from_pool(pool: MySqlPool) -> Self {
        Self { pool }
    }

    /// The underlying connection pool, for sharing with the rest of the app.
    pub fn pool(&self) -> &MySqlPool {
        &self.pool
    }

    /// Run the embedded migrations. Idempotent — safe to call on every
    /// boot.
    pub async fn migrate(&self) -> Result<(), sqlx::migrate::MigrateError> {
        sqlx::migrate!("./migrations/mysql").run(&self.pool).await
    }
}

crate::stores::sqlx_stores! {
    storage: MySqlStorage,
    pool: MySqlPool,
    row: sqlx::mysql::MySqlRow,
    placeholders: crate::common::ph_mysql,
    take: txn,
}
