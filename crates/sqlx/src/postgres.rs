//! Postgres adapter backed by `sqlx::PgPool`.
//!
//! The store logic lives once in the `stores::sqlx_stores` macro; this module
//! supplies only the Postgres specifics — connection setup, the pool/row
//! types, the migration path, and the `$1`/`$2`/… placeholder rewriter
//! (`common::ph_postgres`). The shared storage-conformance suite
//! (`tests/conformance`) runs the same assertions against this expansion and
//! the SQLite one.

use sqlx::PgPool;
use sqlx::postgres::PgPoolOptions;

/// Postgres storage adapter. Construct once at startup and hand
/// `storage()` to `AuthService::builder`, or pull individual stores via the
/// helpers generated by the `stores::sqlx_stores` macro when wiring managers
/// by hand.
#[derive(Clone)]
pub struct PostgresStorage {
    pool: PgPool,
}

impl PostgresStorage {
    /// Pool size [`connect`](Self::connect) opens. A conservative default;
    /// hosts that need different tuning build their own pool and use
    /// [`from_pool`](Self::from_pool).
    pub const DEFAULT_MAX_CONNECTIONS: u32 = 8;

    /// Open a pool against `url`, e.g. `"postgres://user:pass@host/db"`.
    /// Opens [`DEFAULT_MAX_CONNECTIONS`](Self::DEFAULT_MAX_CONNECTIONS)
    /// connections; use [`from_pool`](Self::from_pool) for custom tuning.
    pub async fn connect(url: &str) -> Result<Self, sqlx::Error> {
        let pool = PgPoolOptions::new()
            .max_connections(Self::DEFAULT_MAX_CONNECTIONS)
            .connect(url)
            .await?;
        Ok(Self { pool })
    }

    /// Construct directly from an already-built pool. Useful when the
    /// host wants custom pool tuning.
    pub fn from_pool(pool: PgPool) -> Self {
        Self { pool }
    }

    /// The underlying connection pool, for sharing with the rest of the app.
    pub fn pool(&self) -> &PgPool {
        &self.pool
    }

    /// Run the embedded migrations. Idempotent — safe to call on every
    /// boot.
    pub async fn migrate(&self) -> Result<(), sqlx::migrate::MigrateError> {
        sqlx::migrate!("./migrations/postgres")
            .run(&self.pool)
            .await
    }
}

crate::stores::sqlx_stores! {
    storage: PostgresStorage,
    pool: PgPool,
    row: sqlx::postgres::PgRow,
    placeholders: crate::common::ph_postgres,
}
