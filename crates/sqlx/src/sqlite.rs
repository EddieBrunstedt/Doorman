//! SQLite adapter backed by `sqlx::SqlitePool`.
//!
//! The store logic lives once in the `stores::sqlx_stores` macro; this module
//! supplies only the SQLite specifics — connection setup, the pool/row types,
//! the migration path, and the no-op `?` placeholder rewriter
//! (`common::ph_sqlite`). The shared storage-conformance suite
//! (`tests/conformance`) runs the same assertions against this expansion and
//! the Postgres one.

use sqlx::SqlitePool;
use sqlx::sqlite::{SqliteConnectOptions, SqlitePoolOptions};

/// SQLite storage adapter. Construct once at startup and hand `storage()`
/// to `DoormanAxum::builder`, or pull individual stores via the helpers
/// generated by the `stores::sqlx_stores` macro when wiring managers by hand.
#[derive(Clone)]
pub struct SqliteStorage {
    pool: SqlitePool,
}

impl SqliteStorage {
    /// Open a pool against `url`. For an ephemeral in-memory DB use
    /// `"sqlite::memory:"`; for a file-backed DB use
    /// `"sqlite:///absolute/path/to/db.sqlite?mode=rwc"`.
    pub async fn connect(url: &str) -> Result<Self, sqlx::Error> {
        let opts: SqliteConnectOptions = url.parse()?;
        let pool = SqlitePoolOptions::new()
            .max_connections(8)
            .connect_with(opts.foreign_keys(true).create_if_missing(true))
            .await?;
        Ok(Self { pool })
    }

    /// Construct directly from an already-built pool. Useful when the
    /// host wants custom pool tuning.
    pub fn from_pool(pool: SqlitePool) -> Self {
        Self { pool }
    }

    /// The underlying connection pool, for sharing with the rest of the app.
    pub fn pool(&self) -> &SqlitePool {
        &self.pool
    }

    /// Run the embedded migrations. Idempotent — safe to call on every
    /// boot.
    pub async fn migrate(&self) -> Result<(), sqlx::migrate::MigrateError> {
        sqlx::migrate!("./migrations/sqlite").run(&self.pool).await
    }
}

crate::stores::sqlx_stores! {
    storage: SqliteStorage,
    pool: SqlitePool,
    row: sqlx::sqlite::SqliteRow,
    placeholders: crate::common::ph_sqlite,
}
